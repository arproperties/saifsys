require_once dirname(__DIR__, 3) . '/includes/erp_module_theme.php';

function co_theme_get(PDO $conn, int $companyId): array {
    return erp_theme_get($conn, $companyId, ERP_THEME_MODULE_CONSTRUCTION);
}

function co_theme_save(PDO $conn, int $companyId, array $payload, ?int $userId): array {
