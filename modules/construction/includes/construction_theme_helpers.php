/** @return list<array> */
function co_theme_templates_by_mode(string $mode): array {
    $mode = strtolower($mode) === 'dark' ? 'dark' : 'light';
    return array_values(array_filter(
        co_theme_templates(),
        static fn(array $tpl): bool => ($tpl['mode'] ?? 'light') === $mode
    ));
}

/** @return array<string,string>|null */
function co_theme_template_by_id(string $id): ?array {
    foreach (co_theme_templates() as $tpl) {
        if (($tpl['id'] ?? '') === $id) {
            return $tpl['theme'];
        }
    }
    return null;
}
