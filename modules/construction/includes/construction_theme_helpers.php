}

function co_theme_reset(PDO $conn, int $companyId): bool {
    return erp_theme_reset($conn, $companyId, ERP_THEME_MODULE_CONSTRUCTION);
}

function co_theme_defaults(): array {
    return erp_theme_defaults(ERP_THEME_MODULE_CONSTRUCTION);
}

